package com.utp.smartlab.persistence;

import com.utp.smartlab.entity.EstadoEquipo;
import com.utp.smartlab.repository.EquipoRepository;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.context.ApplicationContextInitializer;
import org.springframework.context.ConfigurableApplicationContext;
import org.springframework.test.context.ContextConfiguration;
import java.sql.DriverManager;
import static org.assertj.core.api.Assertions.assertThat;

@SpringBootTest(properties = {
        "spring.datasource.url=jdbc:h2:mem:estado-legacy;DB_CLOSE_DELAY=-1",
        "spring.jpa.hibernate.ddl-auto=update"
})
@ContextConfiguration(initializers = EquipoSchemaUpdateTest.EsquemaAnterior.class)
class EquipoSchemaUpdateTest {
    @Autowired EquipoRepository equipos;

    public static class EsquemaAnterior implements ApplicationContextInitializer<ConfigurableApplicationContext> {
        public void initialize(ConfigurableApplicationContext context) {
            try (var connection = DriverManager.getConnection("jdbc:h2:mem:estado-legacy;DB_CLOSE_DELAY=-1", "sa", "");
                 var sql = connection.createStatement()) {
                sql.execute("CREATE TABLE categorias (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, nombre VARCHAR(255) NOT NULL)");
                sql.execute("INSERT INTO categorias (id, nombre) VALUES (9001, 'Legado')");
                sql.execute("CREATE TABLE equipos (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, nombre VARCHAR(255) NOT NULL, categoria_id BIGINT NOT NULL, ubicacion VARCHAR(255), estado ENUM('DISPONIBLE','EN_MANTENIMIENTO') NOT NULL, contador_uso_horas INTEGER NOT NULL)");
                sql.execute("INSERT INTO equipos VALUES (9001, 'Disponible existente', 9001, 'Lab', 'DISPONIBLE', 42), (9002, 'Mantenimiento existente', 9001, 'Lab', 'EN_MANTENIMIENTO', 15)");
                sql.execute("CREATE TABLE historial_estado_equipo (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, equipo_id BIGINT NOT NULL, usuario_id BIGINT, estado_anterior ENUM('DISPONIBLE','EN_MANTENIMIENTO'), estado_nuevo ENUM('DISPONIBLE','EN_MANTENIMIENTO') NOT NULL, motivo VARCHAR(255) NOT NULL, fecha_cambio TIMESTAMP NOT NULL)");
                sql.execute("INSERT INTO historial_estado_equipo (equipo_id, estado_anterior, estado_nuevo, motivo, fecha_cambio) VALUES (9001, NULL, 'DISPONIBLE', 'Alta existente', CURRENT_TIMESTAMP)");
                sql.execute("SET MODE MySQL");
                org.springframework.jdbc.datasource.init.ScriptUtils.executeSqlScript(connection,
                        new org.springframework.core.io.ClassPathResource("db/manual/equipos-fuera-de-servicio.sql"));
                sql.execute("INSERT INTO historial_estado_equipo (equipo_id, estado_anterior, estado_nuevo, motivo, fecha_cambio) VALUES (9001, 'FUERA_DE_SERVICIO', 'FUERA_DE_SERVICIO', 'Prueba de ambos campos ampliados', CURRENT_TIMESTAMP)");
            } catch (Exception ex) { throw new IllegalStateException(ex); }
        }
    }

    @Test
    void actualizacionConservaDatosYPermiteElNuevoEstado() {
        var equipo = equipos.findById(9001L).orElseThrow();
        assertThat(equipo.getVersion()).isZero();
        assertThat(equipo.getContadorUsoHoras()).isEqualTo(42);
        assertThat(equipo.getEstado()).isEqualTo(EstadoEquipo.DISPONIBLE);
        assertThat(equipos.findById(9002L).orElseThrow().getEstado()).isEqualTo(EstadoEquipo.EN_MANTENIMIENTO);
        equipo.setEstado(EstadoEquipo.FUERA_DE_SERVICIO);
        equipos.saveAndFlush(equipo);
        assertThat(equipos.findById(9001L).orElseThrow().getEstado()).isEqualTo(EstadoEquipo.FUERA_DE_SERVICIO);
    }
}
